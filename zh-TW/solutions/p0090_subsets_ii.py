"""## Task

Return every distinct subset of an integer array that may contain repeated values. A value can
appear no more times than it occurs in the input.

## Hints

1. Sort equal choices together.
2. For iterative expansion, a repeated value may extend only the subsets created by its previous
   copy.

## Approach

### Depth-local duplicate skipping

Sort a copy, record each path, and choose later indices. Skip equal candidates at the same depth
while permitting equal values deeper in a path.

### Extend only the new subset block

Start with the empty subset. A new value extends all existing subsets; a repeated value extends
only the block created by its immediate predecessor.

## Why it works

### Depth-local duplicate skipping

Every multiset subset has one sorted path. Equal alternatives at a depth generate the same path
family and can be skipped without losing different multiplicities.

### Extend only the new subset block

Subsets containing j copies arise by extending those newly created with j-1 copies. Restricting
the source block prevents recreating subsets already generated by earlier identical values.

## Walkthrough

For [1,2,2], the second 2 extends only [2] and [1,2], creating [2,2] and [1,2,2].

## Cost and pitfalls

Depth-local duplicate skipping: O(n*2^n) loose bound time; O(n) auxiliary plus output space.
Extend only the new subset block: O(n*2^n) loose bound time; O(n*2^n) including output space.
Input is unchanged. Preserve the old result length before appending. Every saved subset must be
a fresh list, and output order need not match a particular traversal.
"""


class Solution:
    """Approach: Depth-local duplicate skipping
    Time: O(n*2^n) loose bound
    Space: O(n) auxiliary plus output
    """

    def subsetsWithDup(self, nums: list[int]) -> list[list[int]]:
        values = sorted(nums)
        result, path = [], []

        def visit(start):
            result.append(path.copy())
            for index in range(start, len(values)):
                if index > start and values[index] == values[index - 1]:
                    continue
                path.append(values[index])
                visit(index + 1)
                path.pop()

        visit(0)
        return result


class IterativeSolution:
    """Approach: Extend only the new subset block
    Time: O(n*2^n) loose bound
    Space: O(n*2^n) including output
    """

    def subsetsWithDup(self, nums: list[int]) -> list[list[int]]:
        values = sorted(nums)
        result = [[]]
        previous_start = 0
        for index, value in enumerate(values):
            start = previous_start if index and value == values[index - 1] else 0
            previous_start = len(result)
            result.extend(result[position] + [value] for position in range(start, previous_start))
        return result
